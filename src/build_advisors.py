def mk(rows, mail_domain="@mail.sysu.edu.cn", url_tpl=None):
    out = []
    for name, title, mail, areas, extra in rows:
        out.append({
            "name": name,
            "title": title,
            "email": (mail + mail_domain) if mail else None,
            "areas": areas,
            "url": (url_tpl.format(extra) if (url_tpl and extra) else None),
            "note": (extra if not url_tpl else None),
            "advises": None,
            "directions": None,
        })
    return out


