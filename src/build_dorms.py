def rooms(rows):
    return [{"building":b,"tier":t,"beds":n,"area":a,"fee":f,"facilities":fac}
            for b,t,n,a,f,fac in rows]

def stats(rows):
    fees = [r[4] for r in rows]
    beds = sorted({r[2] for r in rows})
    return {"min": min(fees), "max": max(fees), "bedTypes": beds}

