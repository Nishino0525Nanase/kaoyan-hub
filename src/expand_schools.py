have = {x["name"] for x in doc["schools"]}

# 给原有条目补上 dataLevel
for x in doc["schools"]:
    x.setdefault("dataLevel", "full")
    x.setdefault("note", None)

added = 0
for name, city, prov, tier, note in NEW:
    if name in have:
        continue
    doc["schools"].append({
        "name": name, "city": city, "province": prov,
        "region": REGION[prov], "zone": "B" if prov in B_ZONE else "A",
        "tier": list(tier), "gradSite": None,
        "aPlus": [], "aCount": 0, "strength": "待补充",
        "dataLevel": "roster", "note": note,
    })
    added += 1

doc["schools"].sort(key=lambda r: (-len(r["aPlus"]) * 3 - r["aCount"], r["name"]))
doc["count"] = len(doc["schools"])
doc["updated"] = "2026-09"
