def strength(a_plus, a_count):
    """按 A+ 学科数与 A 类学科总数给一个粗略的学科实力分档（仅供参考）。"""
    score = len(a_plus) * 3 + a_count
    if score >= 60: return "顶尖"
    if score >= 25: return "很强"
    if score >= 10: return "较强"
    if score >= 3:  return "有特色"
    return "待补充"


